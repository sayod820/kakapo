import fs from 'node:fs'

const FILE = 'components/store/StoreApp.tsx'
let src = fs.readFileSync(FILE, 'utf8')
const EOL = src.includes('\r\n') ? '\r\n' : '\n'
const j = (a) => a.join(EOL)
const cut = (startAnchor, endAnchor, page, label) => {
  const s = src.indexOf(startAnchor)
  const e = src.indexOf(endAnchor)
  if (s < 0 || e <= s) throw new Error(label + ' block not found')
  src = src.slice(0, s) + page + src.slice(e)
}

