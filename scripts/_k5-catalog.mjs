    '  const light = true;',
    '  const { prods, restaurants, restaurantsReady, catalogReady } = useLiveCatalog();',
    '  const { rootCats, cats, ready: catsReady } = useStoreCategories();',
    '  const { isVip } = resolveUserVip(user, light);',
